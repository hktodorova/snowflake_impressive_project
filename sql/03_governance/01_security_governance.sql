ALTER TABLE SILVER.CUSTOMERS_SCD2 SET TAG GOVERNANCE.DATA_OWNER = 'hktodorova@gmail.com';
ALTER TABLE SILVER.CUSTOMERS_SCD2 MODIFY COLUMN email SET TAG GOVERNANCE.DATA_CLASSIFICATION = 'PII';
ALTER TABLE GOLD.DT_CUSTOMER_360 SET TAG GOVERNANCE.SLA_TIER = 'gold-30-minute';

CREATE OR REPLACE MASKING POLICY GOVERNANCE.MASK_EMAIL AS (val STRING) RETURNS STRING ->
  CASE
    WHEN CURRENT_ROLE() IN ('ROLE_DATA_PLATFORM_ADMIN', 'ROLE_DATA_ENGINEER') THEN val
    WHEN val IS NULL THEN NULL
    ELSE REGEXP_REPLACE(val, '(^.).*(@.*$)', '\\1***\\2')
  END;

ALTER TABLE SILVER.CUSTOMERS_SCD2 MODIFY COLUMN email SET MASKING POLICY GOVERNANCE.MASK_EMAIL;

CREATE OR REPLACE ROW ACCESS POLICY GOVERNANCE.COUNTRY_ACCESS_POLICY AS (country STRING) RETURNS BOOLEAN ->
  CURRENT_ROLE() IN ('ROLE_DATA_PLATFORM_ADMIN', 'ROLE_DATA_ENGINEER')
  OR EXISTS (
    SELECT 1
    FROM GOVERNANCE.ALLOWED_COUNTRIES ac
    WHERE ac.country_code = country
      AND ac.is_active = TRUE
  );

ALTER TABLE GOLD.DT_CUSTOMER_360 ADD ROW ACCESS POLICY GOVERNANCE.COUNTRY_ACCESS_POLICY ON (country);

