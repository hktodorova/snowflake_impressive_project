USE DATABASE ECOMMERCE_RT;

-- ALLOWED_COUNTRIES is the source of truth for the row access policy.
-- Add rows here to extend access — no policy redeployment needed.
CREATE TABLE IF NOT EXISTS GOVERNANCE.ALLOWED_COUNTRIES (
  country_code STRING     NOT NULL,
  country_name STRING,
  region       STRING,
  is_active    BOOLEAN    NOT NULL DEFAULT TRUE,
  updated_at   TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_ALLOWED_COUNTRIES PRIMARY KEY (country_code) NOT ENFORCED
);

INSERT INTO GOVERNANCE.ALLOWED_COUNTRIES (country_code, country_name, region, is_active)
SELECT column1, column2, column3, column4
FROM VALUES
  ('US', 'United States',  'Americas', TRUE),
  ('CA', 'Canada',         'Americas', TRUE),
  ('GB', 'United Kingdom', 'Europe',   TRUE),
  ('DE', 'Germany',        'Europe',   TRUE),
  ('FR', 'France',         'Europe',   TRUE)
WHERE NOT EXISTS (SELECT 1 FROM GOVERNANCE.ALLOWED_COUNTRIES);

CREATE TAG IF NOT EXISTS GOVERNANCE.DATA_CLASSIFICATION;
CREATE TAG IF NOT EXISTS GOVERNANCE.DATA_OWNER;
